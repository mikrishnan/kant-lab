#!/usr/bin/env python3
"""translations/meier-phrases.json as a classic script for busolt-reader.html (a page cannot
fetch() JSON from file://): translations/meier-phrases.js, with each phrase as character offsets
into Meier's § text (from meier-auszug.js), so the page cuts the German itself and nothing in it
is altered.

    MEIER_PHRASES[§][k] = [ [start, end, gloss], ... ]   k = the sentence unit, as in MEIER_ALIGNED[§]

    python3 build-meier-phrases-js.py
"""
import json, os, re, subprocess

here = os.path.dirname(os.path.abspath(__file__))
paras = json.loads(subprocess.run(['node', '-e',
    'eval(require("fs").readFileSync("%s","utf8")+";globalThis.M=MEIER_AUSZUG");console.log(JSON.stringify(M.paras))'
    % os.path.join(here, 'meier-auszug.js')], capture_output=True, text=True, check=True).stdout)
doc = json.load(open(os.path.join(here, 'translations', 'meier-phrases.json'), encoding='utf8'))

out, n_ph = {}, 0
for sg in doc['segments']:
    text = paras[str(sg['para'])]
    s0, s1 = sg['offsets']
    seg = text[s0:s1]
    assert re.sub(r'\s+', '', seg) == re.sub(r'\s+', '', sg['de']), (sg['para'], sg['seg'])
    idx = [i for i, ch in enumerate(seg) if not ch.isspace()]
    flat = ''.join(seg[i] for i in idx)
    at, rows = 0, []
    for ph in sg['phrases']:
        f = re.sub(r'\s+', '', ph['de'])
        assert flat.startswith(f, at), (sg['para'], sg['seg'], ph['de'])
        rows.append([s0 + idx[at], s0 + idx[at + len(f) - 1] + 1, ph['en']])
        at += len(f)
    assert at == len(flat)
    lst = out.setdefault(str(sg['para']), [])
    assert len(lst) == sg['seg'] - 1
    lst.append(rows)
    n_ph += len(rows)

with open(os.path.join(here, 'translations', 'meier-phrases.js'), 'w', encoding='utf8') as f:
    f.write('/* Generated by build-meier-phrases-js.py from meier-phrases.json — do not hand-edit.\n'
            '   MEIER_PHRASES[§][k] = [ [start, end, English gloss], … ]: the phrases of sentence unit k of §,\n'
            '   as character offsets into MEIER_AUSZUG.paras[§]. Unreviewed machine glosses. */\n'
            'const MEIER_PHRASES = ' + json.dumps(out, ensure_ascii=False, separators=(',', ':')) + ';\n')
print(len(out), 'paragraphs,', n_ph, 'phrases')
